#!/usr/bin/env python3
"""Rebuild the self-hosted web fonts in docs/assets/fonts/ and their @font-face rules.

All fonts are under the SIL Open Font License 1.1. Each family is cut into a latin and a
latin-ext subset; the browser downloads latin-ext only for pages that need it.

  - IBM Plex Sans, IBM Plex Mono, Kalam: the woff2 subsets published by Fontsource.
  - Source Serif 4, EB Garamond: built here from the variable fonts in google/fonts,
    because the Fontsource subsets drop the small-caps feature (smcp) that the
    Editorial and Stationery voices use.

Usage:  python tools/fonts.py WORKDIR
        (needs: fonttools, brotli; WORKDIR receives the downloads)
Writes: docs/assets/fonts/*.woff2, docs/assets/fonts/OFL-*.txt,
        docs/assets/stylesheets/fonts.css
"""
import io
import json
import pathlib
import sys
import tarfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "docs/assets/fonts"
CSS = ROOT / "docs/assets/stylesheets/fonts.css"

GOOGLE_FONTS = "https://raw.githubusercontent.com/google/fonts/6c1dbe27dcf7d817d4b62cec033ba77fa8e2a5ec/ofl/"
FONTSOURCE = {  # npm package -> version
    "@fontsource/ibm-plex-sans": "5.3.0",
    "@fontsource/ibm-plex-mono": "5.3.0",
    "@fontsource/kalam": "5.3.0",
}

# The same split as Fontsource / Google Fonts, plus the arrows, § and ❧ the voices set.
RANGES = {
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,"
             "U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2190-2193,U+2212,U+2215,U+2767,"
             "U+FEFF,U+FFFD",
    "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,"
                 "U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,"
                 "U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
}
FONTSOURCE_RANGES = {  # Fontsource's own split (its files contain exactly these)
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,"
             "U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,"
             "U+FEFF,U+FFFD",
    "latin-ext": RANGES["latin-ext"],
}

# family, file stem, [(weight, style)], source
PLAN = [
    ("IBM Plex Sans", "ibm-plex-sans", [(400, "normal"), (400, "italic"), (500, "normal"), (600, "normal")], "@fontsource/ibm-plex-sans"),
    ("IBM Plex Mono", "ibm-plex-mono", [(400, "normal"), (400, "italic"), (500, "normal"), (600, "normal")], "@fontsource/ibm-plex-mono"),
    ("Kalam", "kalam", [(400, "normal"), (700, "normal")], "@fontsource/kalam"),
    ("Source Serif 4", "source-serif-4", [(400, "normal"), (400, "italic"), (600, "normal"), (600, "italic")],
     {"normal": "sourceserif4/SourceSerif4[opsz,wght].ttf", "italic": "sourceserif4/SourceSerif4-Italic[opsz,wght].ttf",
      "ofl": "sourceserif4/OFL.txt", "pin": {"opsz": 20}}),
    ("EB Garamond", "eb-garamond", [(400, "normal"), (400, "italic"), (500, "normal"), (500, "italic"), (600, "normal")],
     {"normal": "ebgaramond/EBGaramond[wght].ttf", "italic": "ebgaramond/EBGaramond-Italic[wght].ttf",
      "ofl": "ebgaramond/OFL.txt", "pin": {}}),
]
FEATURES = ["kern", "liga", "clig", "calt", "ccmp", "locl", "mark", "mkmk", "smcp", "c2sc",
            "onum", "lnum", "pnum", "tnum", "frac", "numr", "dnom", "ordn", "sups", "case"]


def fetch(url, dest):
    if not dest.exists():
        dest.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url) as r:
            dest.write_bytes(r.read())
    return dest


def fontsource(pkg, work):
    version = FONTSOURCE[pkg]
    name = pkg.split("/")[1]
    tgz = fetch(f"https://registry.npmjs.org/{pkg}/-/{name}-{version}.tgz", work / f"{name}-{version}.tgz")
    out = work / f"{name}-{version}"
    if not out.exists():
        with tarfile.open(tgz) as t:
            t.extractall(out, filter="data")
    return out / "package"


def unicodes(spec):
    cps = []
    for part in spec.split(","):
        a, _, b = part[2:].partition("-")
        cps.extend(range(int(a, 16), int(b or a, 16) + 1))
    return cps


def main(work):
    work = pathlib.Path(work).resolve()
    FONTS.mkdir(parents=True, exist_ok=True)
    for old in FONTS.glob("*.woff2"):
        old.unlink()
    for old in FONTS.glob("OFL-*.txt"):
        old.unlink()
    rules = ["/* Generated by tools/fonts.py. Self-hosted fonts, SIL Open Font License 1.1\n"
             "   (see ../fonts/OFL-*.txt). Subsets latin + latin-ext. A face is downloaded\n"
             "   only when text on the page uses it, so each voice loads only its own. */"]
    for family, stem, faces, source in PLAN:
        lic = "OFL-" + family.replace(" ", "") + ".txt"
        if isinstance(source, str):
            pkg = fontsource(source, work)
            (FONTS / lic).write_bytes((pkg / "LICENSE").read_bytes())
            ranges = FONTSOURCE_RANGES
            for sub in ("latin-ext", "latin"):
                for w, st in faces:
                    f = f"{stem}-{sub}-{w}-{st}.woff2"
                    (FONTS / f).write_bytes((pkg / "files" / f).read_bytes())
                    rules.append(face(family, st, w, f, ranges[sub]))
        else:
            (FONTS / lic).write_bytes(fetch(GOOGLE_FONTS + source["ofl"], work / "gf" / source["ofl"]).read_bytes())
            for w, st in faces:
                src = fetch(GOOGLE_FONTS + source[st].replace("[", "%5B").replace("]", "%5D"), work / "gf" / source[st])
                static = instancer.instantiateVariableFont(TTFont(src), {"wght": w, **source["pin"]})
                buf = io.BytesIO()
                static.save(buf)
                for sub in ("latin-ext", "latin"):
                    font = TTFont(io.BytesIO(buf.getvalue()))
                    opts = subset.Options()
                    opts.flavor = "woff2"
                    opts.layout_features = FEATURES
                    opts.name_IDs = ["*"]
                    opts.notdef_outline = True
                    opts.hinting = False
                    opts.drop_tables += ["DSIG"]
                    s = subset.Subsetter(opts)
                    s.populate(unicodes=unicodes(RANGES[sub]))
                    s.subset(font)
                    f = f"{stem}-{sub}-{w}-{st}.woff2"
                    font.flavor = "woff2"
                    font.save(FONTS / f)
                    rules.append(face(family, st, w, f, RANGES[sub]))
    CSS.write_text("\n".join(rules) + "\n")
    total = sum(p.stat().st_size for p in FONTS.glob("*.woff2"))
    print(json.dumps({"files": len(list(FONTS.glob("*.woff2"))), "bytes": total}))


def face(family, style, weight, file, rng):
    return (f'@font-face{{font-family:"{family}";font-style:{style};font-weight:{weight};'
            f'font-display:swap;src:url(../fonts/{file}) format("woff2");unicode-range:{rng}}}')


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".fontsrc")
